import { expect, test, type Page } from "@playwright/test";
import { accountsSession, runAccounts, sameOrigin, signIn, watchErrors } from "./support";
import { audit } from "./audit";

async function select(page: Page, address: string) {
  await page.getByTestId("name-box").click();
  await page.getByTestId("name-box").fill(address);
  await page.getByTestId("name-box").press("Enter");
  await expect(page.getByTestId("name-box")).toHaveValue(address);
}
async function enter(page: Page, address: string, text: string) {
  await select(page, address);
  await page.getByTestId("cell-input").focus();
  await page.keyboard.type(text);
  await page.keyboard.press("Enter");
}
async function custom(page: Page, label: string) {
  await page.getByRole("button", { name: /^Number format / }).click();
  await page.getByRole("menuitem", { name: label, exact: true }).click();
}

test("checkboxes and dropdowns keep typed values, formulas, undo, copies and read-only access", async ({ browser }) => {
  const context = await accountsSession(browser, "carbon", { bypassCSP: true, reducedMotion: "reduce" });
  const page = await context.newPage();
  const errors = watchErrors(page);
  await signIn(page, runAccounts().carbon.email);
  await page.getByRole("button", { name: "New sheet", exact: true }).click();
  await expect(page.getByTestId("grid")).toBeVisible();
  const path = new URL(page.url()).pathname;
  const id = path.split("/")[2];
  const cells = async () => (await (await page.request.get(`/api/v1/sheets/${id}/tabs/1/cells?range=A1:F8`)).json());
  const value = async (address: string) => (await cells()).cells.find((cell: { a: string }) => cell.a === address)?.v;
  await select(page, "A1:A3");
  await page.getByRole("button", { name: "Insert checkbox", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Checkbox A1", exact: true })).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "Checkbox A3", exact: true })).toBeVisible();
  await enter(page, "B1", "=IF(A1,10,0)");
  await page.getByRole("checkbox", { name: "Checkbox A1", exact: true }).click();
  await expect.poll(() => value("B1")).toEqual({ t: "number", v: 10 });
  await page.getByTestId("cell-input").press("Space");
  await expect.poll(() => value("A1")).toEqual({ t: "bool", v: false });
  await page.getByRole("button", { name: "Undo your last change", exact: true }).click();
  await expect.poll(() => value("A1")).toEqual({ t: "bool", v: true });
  await select(page, "A2");
  await page.getByRole("button", { name: "Cell controls", exact: true }).click();
  await page.getByRole("menuitem", { name: "Custom checkbox values…", exact: true }).click();
  await page.getByRole("checkbox", { name: "Use custom cell values", exact: true }).click();
  await page.getByRole("textbox", { name: "Checked", exact: true }).fill("Approved");
  await page.getByRole("textbox", { name: "Unchecked", exact: true }).fill("Waiting");
  await audit(page, "custom checkbox values");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await page.getByRole("checkbox", { name: "Checkbox A2", exact: true }).click();
  await expect.poll(() => value("A2")).toEqual({ t: "text", v: "Approved" });
  await select(page, "C1:C3");
  await page.getByRole("button", { name: "Cell controls", exact: true }).click();
  await page.getByRole("menuitem", { name: "Dropdown…", exact: true }).click();
  await page.getByRole("textbox", { name: "Options, one per line", exact: true }).fill("To do\nDone\n=1+2");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await page.getByRole("combobox", { name: "Dropdown C1", exact: true }).selectOption("=1+2");
  await expect.poll(() => value("C1")).toEqual({ t: "text", v: "=1+2" });
  await select(page, "A1");
  await page.getByRole("button", { name: "Clear formatting", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Checkbox A1", exact: true })).toBeChecked();
  await page.reload();
  await expect(page.getByRole("checkbox", { name: "Checkbox A1", exact: true })).toBeChecked();
  await expect(page.getByRole("combobox", { name: "Dropdown C1", exact: true })).toHaveValue("=1+2");
  await audit(page, "in-cell checkbox and dropdown controls");
  await page.screenshot({ path: "screens/cell-controls.png" });
  const copy = await page.request.post(`/api/v1/sheets/${id}/copies`, { headers: sameOrigin(), data: { name: "Controls copy" } });
  expect(copy.ok()).toBeTruthy();
  const copied = await page.request.get(`/api/v1/sheets/${id}/copies/${(await copy.json()).id}/tabs/1/cells?range=A1:C3`);
  expect(Object.values((await copied.json()).styles)).toEqual(expect.arrayContaining([expect.objectContaining({ control: { kind: "checkbox" } }), expect.objectContaining({ control: { kind: "dropdown", options: ["To do", "Done", "=1+2"] } })]));
  await page.request.put(`/api/v1/sheets/${id}/public`, { headers: sameOrigin(), data: { enabled: true, access: "view" } });
  const guest = await browser.newContext();
  const visitor = await guest.newPage();
  await visitor.goto(page.url());
  await expect(visitor.getByRole("checkbox", { name: "Checkbox A1", exact: true })).toBeDisabled();
  await expect(visitor.getByRole("combobox", { name: "Dropdown C1", exact: true })).toBeDisabled();
  await guest.close();
  expect(errors).toEqual([]);
  await context.close();
});

test("standard, custom, currency and text formats agree with their previews and persist", async ({ browser }) => {
  const context = await accountsSession(browser, "carbon", { bypassCSP: true, reducedMotion: "reduce" });
  const page = await context.newPage();
  const errors = watchErrors(page);
  await signIn(page, runAccounts().carbon.email);
  await page.getByRole("button", { name: "New sheet", exact: true }).click();
  await expect(page.getByTestId("grid")).toBeVisible();
  const id = new URL(page.url()).pathname.split("/")[2];
  const cell = async (address: string) => (await (await page.request.get(`/api/v1/sheets/${id}/tabs/1/cells?range=${address}`)).json()).cells[0];
  await enter(page, "A1", "-1234.5");
  await select(page, "A1");
  await custom(page, "Custom number format…");
  await page.getByRole("textbox", { name: "Format", exact: true }).fill('#,##0.00;[Red](#,##0.00);"–"');
  await expect(page.getByRole("status").filter({ hasText: "(1,234.50)" })).toBeVisible();
  await audit(page, "custom number format preview");
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await expect.poll(async () => (await cell("A1")).t).toBe("(1,234.50)");
  expect((await cell("A1")).tc).toBe("#C00000");
  await enter(page, "A2", "1.5");
  await select(page, "A2");
  await page.getByRole("button", { name: /^Number format / }).click();
  await page.getByRole("menuitemradio", { name: /^Fraction / }).click();
  await expect.poll(async () => (await cell("A2")).t).toBe("1 1/2");
  await enter(page, "A3", "1234.5");
  await select(page, "A3");
  await expect.poll(async () => (await cell("A3"))?.v).toEqual({ t: "number", v: 1234.5 });
  await custom(page, "Custom currency…");
  await page.getByRole("combobox", { name: "Currency", exact: true }).click();
  await page.getByRole("option", { name: /^INR / }).click();
  await expect(page.getByRole("status").filter({ hasText: "₹1,234.50" })).toBeVisible();
  await page.getByRole("button", { name: "Apply", exact: true }).click();
  await expect.poll(async () => (await cell("A3")).t).toBe("₹1,234.50");
  await select(page, "B1:B2");
  await page.getByRole("button", { name: /^Number format / }).click();
  await page.getByRole("menuitemradio", { name: /^Plain text / }).click();
  await expect.poll(async () => { const response = await page.request.get(`/api/v1/sheets/${id}/tabs/1/cells?range=B1:B2`); return Object.values((await response.json()).styles); }).toEqual(expect.arrayContaining([expect.objectContaining({ num_fmt: "@" })]));
  await enter(page, "B1", "00123");
  await enter(page, "B2", "=1+2");
  await expect.poll(async () => (await cell("B2")).v).toEqual({ t: "text", v: "=1+2" });
  await select(page, "B1");
  await page.getByRole("button", { name: "Text layout", exact: true }).click();
  await page.getByRole("menuitemradio", { name: "Clip", exact: true }).click();
  await page.getByRole("button", { name: "Text layout", exact: true }).click();
  await page.getByRole("menuitemradio", { name: "Tilt up", exact: true }).click();
  await page.reload();
  await select(page, "B1");
  await page.getByRole("button", { name: "Text layout", exact: true }).click();
  await expect(page.getByRole("menuitemradio", { name: "Clip", exact: true })).toHaveAttribute("aria-checked", "true");
  await expect(page.getByRole("menuitemradio", { name: "Tilt up", exact: true })).toHaveAttribute("aria-checked", "true");
  await page.keyboard.press("Escape");
  expect((await cell("B1")).v).toEqual({ t: "text", v: "00123" });
  expect(errors).toEqual([]);
  await page.screenshot({ path: "screens/cell-formats.png" });
  await context.close();
});
